CREATE TABLE EMS_APP.EMPLOYEES
(
    EMPLOYEE_ID NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    FIRST_NAME VARCHAR2(50 CHAR) NOT NULL,
    LAST_NAME VARCHAR2(50 CHAR) NOT NULL,
    DEPARTMENT VARCHAR2(100 CHAR) NOT NULL,
    DESIGNATION VARCHAR2(100 CHAR) NOT NULL,
    SALARY NUMBER(12,2) NOT NULL,
    DATE_OF_JOINING DATE NOT NULL,
    CONSTRAINT PK_EMPLOYEES PRIMARY KEY (EMPLOYEE_ID),
    CONSTRAINT CK_EMPLOYEES_SALARY CHECK (SALARY > 0)
);

CREATE INDEX EMS_APP.IX_EMPLOYEES_NAME
    ON EMS_APP.EMPLOYEES (LAST_NAME, FIRST_NAME);
